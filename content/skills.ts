export const SKILL_MAP: Record<string, Skill> = Object.fromEntries(SKILLS.map((s) => [s.id, s]));

export function skillLabel(id: string): string {
  return SKILL_MAP[id]?.label ?? id;
}

// Map free text (an ELSA note, a self-reported error) to the most likely skill ids.
// Pure keyword matching: the result is a suggestion the learner confirms.
export function matchSkills(text: string): string[] {
  const t = text.toLowerCase();
  const scored = SKILLS.map((s) => {
    let score = 0;
    for (const k of s.keywords) {
      if (k.length <= 2 && /^[a-z/]+$/.test(k)) {
        // short latin keys like "th" / "v" need a word boundary to avoid noise
        const re = new RegExp(`(^|[^a-z])${k.replace(/[/]/g, "\\/")}([^a-z]|$)`);
        if (re.test(t)) score += 1;
      } else if (t.includes(k.toLowerCase())) score += 2;
    }
    for (const w of s.words) if (w.split(" ").length === 1 && new RegExp(`\\b${w.toLowerCase()}\\b`).test(t)) score += 1;
    return { id: s.id, score };
  })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score);
  return scored.slice(0, 3).map((x) => x.id);
}
